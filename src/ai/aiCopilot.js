/**
 * CanvasCord AI Design Copilot & Natural Language Synthesis Engine
 * Integrates Hugging Face Open-Source LLMs + High-Precision Procedural Layout Heuristics
 */

import { createElement } from '../canvas/elements.js';
import {
  createSaaSHeroTemplate,
  createMobileAppTemplate,
  createPricingTableTemplate,
} from './templates.js';
import { HuggingFaceClient } from './huggingFaceClient.js';

export class AICopilot {
  constructor(engine, onElementAdded) {
    this.engine = engine;
    this.onElementAdded = onElementAdded || (() => {});
    this.hfClient = new HuggingFaceClient();
  }

  async processPrompt(promptText) {
    const raw = promptText.toLowerCase();
    const cx = Math.round(-this.engine.viewport.x + this.engine.width / (2 * this.engine.viewport.zoom));
    const cy = Math.round(-this.engine.viewport.y + this.engine.height / (2 * this.engine.viewport.zoom));

    // 1. Check if Hugging Face API is active and requested
    if (this.hfClient.hasApiKey() && !raw.includes('audit') && !raw.includes('critique')) {
      const hfResult = await this.hfClient.generateDesignFromPrompt(promptText, { x: cx, y: cy });
      if (hfResult.success && Array.isArray(hfResult.elements)) {
        const validatedElements = hfResult.elements.map(item => {
          return createElement(item.type || 'rect', {
            name: item.name || 'AI Element',
            x: item.x ?? cx,
            y: item.y ?? cy,
            width: item.width ?? 120,
            height: item.height ?? 80,
            fill: item.fill ?? '#5865F2',
            stroke: item.stroke ?? '#35373c',
            strokeWidth: item.strokeWidth ?? 0,
            cornerRadius: item.cornerRadius ?? 8,
            text: item.text,
            fontSize: item.fontSize,
            fontWeight: item.fontWeight,
            fontColor: item.fontColor,
            shadow: item.shadow,
          });
        });

        this.engine.elements.push(...validatedElements);
        this.engine.selectedIds.clear();
        validatedElements.forEach(el => this.engine.selectedIds.add(el.id));
        this.engine.requestRender();
        this.onElementAdded();

        return `✨ **Generated by Hugging Face (${this.hfClient.selectedModel})**:\nSynthesized ${validatedElements.length} vector elements for *"\\${promptText}"*.`;
      }
    }

    // 2. High-Precision Design System Templates & Heuristic Synthesizers
    if (raw.includes('hero') || raw.includes('landing')) {
      const els = createSaaSHeroTemplate(
        -this.engine.viewport.x + 80,
        -this.engine.viewport.y + 60
      );
      this.engine.elements.push(...els);
      this.engine.requestRender();
      this.onElementAdded();
      return `✨ Synthesized **Modern SaaS Landing Page Hero Section** (1440px desktop frame with navbar, typography, CTA buttons, and ambient blurple lighting).`;
    }

    if (raw.includes('mobile') || raw.includes('phone') || raw.includes('music')) {
      const els = createMobileAppTemplate(
        -this.engine.viewport.x + 120,
        -this.engine.viewport.y + 60
      );
      this.engine.elements.push(...els);
      this.engine.requestRender();
      this.onElementAdded();
      return `📱 Synthesized **iOS 16 Mobile Music Player** (390×844 frame with Dynamic Island, album art card, progress scrubbing bar, and media controls).`;
    }

    if (raw.includes('pricing') || raw.includes('tier')) {
      const els = createPricingTableTemplate(
        -this.engine.viewport.x + 100,
        -this.engine.viewport.y + 80
      );
      this.engine.elements.push(...els);
      this.engine.requestRender();
      this.onElementAdded();
      return `💳 Synthesized **3-Tier SaaS Pricing Matrix** (Starter, Pro Featured, and Enterprise packages with feature checklists).`;
    }

    // 3. Checkout Funnel / Card Component
    if (raw.includes('checkout') || raw.includes('payment') || raw.includes('card')) {
      const frame = createElement('frame', {
        name: 'Frame // Checkout Dialog',
        x: cx - 180,
        y: cy - 220,
        width: 360,
        height: 440,
        fill: '#1e1f22',
        stroke: '#35373c',
        strokeWidth: 1,
        cornerRadius: 16,
      });
      const title = createElement('text', {
        name: 'Checkout Title',
        x: cx - 150,
        y: cy - 180,
        text: 'Confirm & Pay\n$49.00 USD',
        fontSize: 22,
        fontWeight: '700',
        fontColor: '#F2F3F5',
        lineHeight: 1.4,
      });
      const inputBg = createElement('rect', {
        name: 'Card Input Field',
        x: cx - 150,
        y: cy - 90,
        width: 300,
        height: 48,
        fill: '#2b2d31',
        stroke: '#35373c',
        strokeWidth: 1,
        cornerRadius: 8,
      });
      const inputLabel = createElement('text', {
        name: 'Card Number Placeholder',
        x: cx - 134,
        y: cy - 76,
        text: '••••  ••••  ••••  4242',
        fontSize: 14,
        fontFamily: 'monospace',
        fontColor: '#949BA4',
      });
      const payBtn = createElement('rect', {
        name: 'Pay Button',
        x: cx - 150,
        y: cy + 120,
        width: 300,
        height: 52,
        fill: '#5865F2',
        cornerRadius: 10,
        shadow: { enabled: true, x: 0, y: 8, blur: 24, color: 'rgba(88, 101, 242, 0.4)' },
      });
      const payText = createElement('text', {
        name: 'Pay Button Label',
        x: cx - 70,
        y: cy + 136,
        text: 'Pay with Apple Pay',
        fontSize: 15,
        fontWeight: '600',
        fontColor: '#ffffff',
      });

      this.engine.elements.push(frame, title, inputBg, inputLabel, payBtn, payText);
      this.engine.requestRender();
      this.onElementAdded();
      return `💳 Generated **Dark Mode Checkout Card** with credit card input and Apple Pay button.`;
    }

    // 4. Analytics / Stats Metric Cards
    if (raw.includes('stats') || raw.includes('metrics') || raw.includes('analytics') || raw.includes('dashboard')) {
      const metrics = [
        { title: 'Total Revenue', value: '$84,230', change: '+18.4% vs last mo', color: '#57F287' },
        { title: 'Active Designers', value: '14,892', change: '+12.1% online', color: '#5865F2' },
        { title: 'Voice Huddles RTC', value: '3,140 hrs', change: '99.98% reliability', color: '#FEE75C' },
      ];

      metrics.forEach((m, idx) => {
        const startX = cx - 360 + idx * 240;
        const card = createElement('rect', {
          name: `Metric Card // ${m.title}`,
          x: startX,
          y: cy - 60,
          width: 220,
          height: 120,
          fill: '#2b2d31',
          stroke: '#35373c',
          strokeWidth: 1,
          cornerRadius: 12,
          shadow: { enabled: true, x: 0, y: 4, blur: 16, color: 'rgba(0,0,0,0.3)' },
        });
        const t1 = createElement('text', {
          name: 'Label',
          x: startX + 16,
          y: cy - 44,
          text: m.title,
          fontSize: 12,
          fontWeight: '500',
          fontColor: '#949BA4',
        });
        const t2 = createElement('text', {
          name: 'Value',
          x: startX + 16,
          y: cy - 20,
          text: m.value,
          fontSize: 24,
          fontWeight: '700',
          fontColor: '#F2F3F5',
        });
        const t3 = createElement('text', {
          name: 'Delta',
          x: startX + 16,
          y: cy + 18,
          text: m.change,
          fontSize: 12,
          fontWeight: '600',
          fontColor: m.color,
        });
        this.engine.elements.push(card, t1, t2, t3);
      });

      this.engine.requestRender();
      this.onElementAdded();
      return `📊 Generated **3-Column Analytics KPI Metric Cards** with performance deltas.`;
    }

    // 5. Button Synthesis
    if (raw.includes('button')) {
      const labelMatch = promptText.match(/["'](.*?)["']/);
      const label = labelMatch ? labelMatch[1] : 'Action Button';
      const color = raw.includes('green') || raw.includes('emerald') ? '#57F287' : (raw.includes('red') ? '#ED4245' : '#5865F2');

      const btn = createElement('rect', {
        name: `Button // ${label}`,
        x: cx - 80,
        y: cy - 25,
        width: 160,
        height: 50,
        fill: color,
        cornerRadius: raw.includes('round') ? 999 : 10,
        shadow: { enabled: true, x: 0, y: 6, blur: 20, color: 'rgba(0,0,0,0.3)' },
      });
      const txt = createElement('text', {
        name: `Label // ${label}`,
        x: cx - 50,
        y: cy - 10,
        text: label,
        fontSize: 15,
        fontWeight: '600',
        fontColor: color === '#57F287' ? '#000000' : '#ffffff',
      });

      this.engine.elements.push(btn, txt);
      this.engine.requestRender();
      this.onElementAdded();
      return `🔘 Spawned high-contrast UI Button **"${label}"** at center viewport.`;
    }

    // 6. Color Palette Generation
    if (raw.includes('palette') || raw.includes('color')) {
      const colors = raw.includes('cyberpunk')
        ? ['#00F0FF', '#FF007F', '#7000FF', '#FFE600', '#05050A']
        : (raw.includes('sunset') ? ['#FF4E50', '#FC913A', '#F9D423', '#EDE574', '#E1F5C4'] : ['#5865F2', '#57F287', '#FEE75C', '#EB459E', '#ED4245']);

      colors.forEach((hex, idx) => {
        const swatch = createElement('rect', {
          name: `Swatch ${idx + 1} (${hex})`,
          x: cx - 220 + idx * 90,
          y: cy - 50,
          width: 76,
          height: 100,
          fill: hex,
          cornerRadius: 12,
          shadow: { enabled: true, x: 0, y: 4, blur: 12, color: 'rgba(0,0,0,0.3)' },
        });
        const label = createElement('text', {
          name: `Hex Label ${idx + 1}`,
          x: cx - 220 + idx * 90 + 8,
          y: cy + 60,
          text: hex,
          fontSize: 12,
          fontWeight: '600',
          fontColor: '#949BA4',
        });
        this.engine.elements.push(swatch, label);
      });

      this.engine.requestRender();
      this.onElementAdded();
      return `🎨 Generated 5-step harmonious design palette on canvas!`;
    }

    // 7. Design Audit / Critique
    if (raw.includes('audit') || raw.includes('critique')) {
      const count = this.engine.elements.length;
      return `🔍 **AI Design System Audit**:\n` +
        `• **Canvas Density**: ${count} active layers.\n` +
        `• **Visual Hierarchy**: Excellent distinction between headers (44px) and body copy.\n` +
        `• **Color Contrast**: Dark mode background (#111215) with Discord Blurple (#5865F2) achieves 7.4:1 contrast ratio (WCAG AAA).\n` +
        `• **Recommendation**: Ensure touch targets on mobile frames maintain a minimum 48×48px clickable boundary.`;
    }

    // 8. Natural Language Feedback Modifications (e.g. "change color to ...")
    if (this.engine.selectedIds.size > 0 && (raw.includes('change') || raw.includes('make') || raw.includes('color'))) {
      let modifiedCount = 0;
      for (const id of this.engine.selectedIds) {
        const el = this.engine.elements.find(i => i.id === id);
        if (!el) continue;
        if (raw.includes('green') || raw.includes('emerald')) el.fill = '#57F287';
        if (raw.includes('blue') || raw.includes('blurple')) el.fill = '#5865F2';
        if (raw.includes('red')) el.fill = '#ED4245';
        if (raw.includes('yellow')) el.fill = '#FEE75C';
        if (raw.includes('round') || raw.includes('radius')) el.cornerRadius = 16;
        modifiedCount++;
      }
      this.engine.requestRender();
      this.onElementAdded();
      return `⚡ Applied natural language modifications to ${modifiedCount} selected canvas layers.`;
    }

    // Fallback Sticky Note
    const note = createElement('sticky', {
      name: 'AI Response Note',
      x: cx - 90,
      y: cy - 80,
      text: `🤖 AI Copilot:\nProcessed: "${promptText}".\nTip: Connect your Hugging Face API key in AI Settings for unrestricted custom generative modeling!`,
      fill: '#5865F2',
      fontColor: '#ffffff',
      author: 'Canvas AI Bot',
    });
    this.engine.elements.push(note);
    this.engine.requestRender();
    this.onElementAdded();
    return `📝 Dropped generated copilot note for prompt: *"${promptText}"*`;
  }
}
